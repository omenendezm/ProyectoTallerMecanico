CREATE TABLE CLIENTE (
    ID_CLIENTE   NUMBER(10)     PRIMARY KEY,
    DPI          VARCHAR2(13)   NOT NULL,
    NOMBRE       VARCHAR2(60)   NOT NULL,
    APELLIDO     VARCHAR2(60)   NOT NULL,
    TELEFONO     VARCHAR2(15),
    CORREO       VARCHAR2(80),
    DIRECCION    VARCHAR2(150),
    CONSTRAINT UQ_CT_DPI UNIQUE (DPI)
);

CREATE TABLE MECANICO (
    ID_MECANICO  NUMBER(10)     PRIMARY KEY,
    DPI          VARCHAR2(13)   NOT NULL,
    NOMBRE       VARCHAR2(60)   NOT NULL,
    APELLIDO     VARCHAR2(60)   NOT NULL,
    TELEFONO     VARCHAR2(15),
    ESPECIALIDAD VARCHAR2(60),
    CONSTRAINT UQ_MECANICO_DPI UNIQUE (DPI)
);

CREATE TABLE VEHICULO_TALLER (
    ID_VEHICULO  NUMBER(10)     PRIMARY KEY,
    PLACA        VARCHAR2(10)   NOT NULL,
    ID_CLIENTE   NUMBER(10)     NOT NULL,
    MARCA        VARCHAR2(40)   NOT NULL,
    MODELO       VARCHAR2(40)   NOT NULL,
    ANIO         NUMBER(4)      NOT NULL,
    COLOR        VARCHAR2(30),
    CONSTRAINT UQ_VT_PLACA UNIQUE (PLACA),
    CONSTRAINT FK_VT_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT CK_VT_ANIO CHECK (ANIO BETWEEN 1950 AND 2100)
);

CREATE TABLE REPUESTO (
    ID_REPUESTO  NUMBER(10)     PRIMARY KEY,
    NOMBRE       VARCHAR2(80)   NOT NULL,
    DESCRIPCION  VARCHAR2(200),
    PRECIO       NUMBER(10,2)   NOT NULL,
    EXISTENCIA   NUMBER(8)      DEFAULT 0 NOT NULL,
    CONSTRAINT CK_REPUESTO_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_REPUESTO_EXISTENCIA CHECK (EXISTENCIA >= 0)
);

CREATE TABLE ABASTECIMIENTO (
    ID_ABASTECIMIENTO NUMBER(10) PRIMARY KEY,
    ID_REPUESTO  NUMBER(10)     NOT NULL,
    CANTIDAD     NUMBER(8)      NOT NULL,
    FECHA        DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_ABAST_REPUESTO FOREIGN KEY (ID_REPUESTO) REFERENCES REPUESTO (ID_REPUESTO),
    CONSTRAINT CK_ABAST_CANTIDAD CHECK (CANTIDAD > 0)
);

CREATE TABLE SERVICIO (
    ID_SERVICIO     NUMBER(10)   PRIMARY KEY,
    DESCRIPCION     VARCHAR2(100) NOT NULL,
    COSTO_MANO_OBRA NUMBER(10,2) NOT NULL,
    CONSTRAINT CK_SERVICIO_COSTO CHECK (COSTO_MANO_OBRA >= 0)
);

CREATE TABLE ORDEN_TRABAJO (
    ID_ORDEN             NUMBER(10)    PRIMARY KEY,
    ID_VEHICULO          NUMBER(10)    NOT NULL,
    ID_MECANICO          NUMBER(10)    NOT NULL,
    DESCRIPCION_PROBLEMA VARCHAR2(400) NOT NULL,
    ESTADO               VARCHAR2(12)  DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_INGRESO        DATE          DEFAULT SYSDATE NOT NULL,
    FECHA_FINALIZACION   DATE,
    TOTAL_MANO_OBRA      NUMBER(12,2)  DEFAULT 0 NOT NULL,
    TOTAL_REPUESTOS      NUMBER(12,2)  DEFAULT 0 NOT NULL,
    TOTAL                NUMBER(12,2)  DEFAULT 0 NOT NULL,
    CONSTRAINT FK_OT_VEHICULO FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULO_TALLER (ID_VEHICULO),
    CONSTRAINT FK_OT_MECANICO FOREIGN KEY (ID_MECANICO) REFERENCES MECANICO (ID_MECANICO),
    CONSTRAINT CK_OT_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'EN PROCESO', 'FINALIZADA', 'CANCELADA'))
);

CREATE TABLE ORDEN_SERVICIO (
    ID_ORDEN_SERVICIO NUMBER(10)   PRIMARY KEY,
    ID_ORDEN          NUMBER(10)   NOT NULL,
    ID_SERVICIO       NUMBER(10)   NOT NULL,
    COSTO             NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_OS_ORDEN FOREIGN KEY (ID_ORDEN) REFERENCES ORDEN_TRABAJO (ID_ORDEN),
    CONSTRAINT FK_OS_SERVICIO FOREIGN KEY (ID_SERVICIO) REFERENCES SERVICIO (ID_SERVICIO),
    CONSTRAINT UQ_OS UNIQUE (ID_ORDEN, ID_SERVICIO),
    CONSTRAINT CK_OS_COSTO CHECK (COSTO >= 0)
);

CREATE TABLE ORDEN_REPUESTO (
    ID_ORDEN_REPUESTO NUMBER(10)   PRIMARY KEY,
    ID_ORDEN          NUMBER(10)   NOT NULL,
    ID_REPUESTO       NUMBER(10)   NOT NULL,
    CANTIDAD          NUMBER(8)    NOT NULL,
    PRECIO_UNITARIO   NUMBER(10,2) NOT NULL,
    SUBTOTAL          NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_OR_ORDEN FOREIGN KEY (ID_ORDEN) REFERENCES ORDEN_TRABAJO (ID_ORDEN),
    CONSTRAINT FK_OR_REPUESTO FOREIGN KEY (ID_REPUESTO) REFERENCES REPUESTO (ID_REPUESTO),
    CONSTRAINT CK_OR_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_OR_PRECIO CHECK (PRECIO_UNITARIO >= 0)
);

